"""Collection Transformer compatible overlays on the immutable source workbook."""
from copy import copy, deepcopy
from dataclasses import replace
from pathlib import Path
import os
import uuid

from openpyxl import Workbook, load_workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.datavalidation import DataValidation

from .spreadsheet_source import SourceLayout, iter_source_rows, normalize_header


OUTPUT_FIELDS = {
    "Claim ID / TRN": "claim_id", "Billed Amount": "total_charges",
    "Paid amount": "paid_amount", "Claim status": "claim_status",
    "Denial Reason": "denial_reason", "Last Action Taken": "last_action_taken",
    "Finalized Date": "finalized_date", "Payment/Check Number": "check_number",
    "Payment/Check Date": "check_date", "Recheck": "recheck",
}
TRACKING = {"Last Action Taken", "Recheck"}


def recheck_disabled(value):
    return str(value).strip().casefold() in {"no", "n", "false", "0"}


def apply_ct_output_styling(ws, header_row=1, last_row=None):
    last_row = last_row or ws.max_row
    ws.sheet_view.showGridLines = True
    minimum_widths = {"Claim ID / TRN": 16, "Billed Amount": 14, "Paid amount": 14,
                      "Claim status": 14, "Denial Reason": 20, "Last Action Taken": 20,
                      "Finalized Date": 14, "Payment/Check Number": 16,
                      "Payment/Check Date": 14, "Recheck": 12}
    columns = []
    for cells in ws.iter_cols(min_row=header_row, max_row=last_row):
        name = cells[0].value
        if normalize_header(name) in {"lat", "lastactiontaken", "lastaction"}:
            name = "Last Action Taken"
        elif normalize_header(name) == "recheck":
            name = "Recheck"
        if name in OUTPUT_FIELDS:
            columns.append((name, cells))
    if not columns:
        return
    ws.row_dimensions[header_row].height = 26
    for row in range(header_row + 1, last_row + 1):
        ws.row_dimensions[row].height = 20
    edge = Side(style="thin", color="D3D3D3")
    border = Border(left=edge, right=edge, top=edge, bottom=edge)
    for name, cells in columns:
        header = cells[0]
        header.font = Font(name="Calibri", size=11, bold=True, color="000000")
        header.fill = PatternFill("solid", fgColor="D9E1F2")
        header.border = border
        header.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        for cell in cells[1:]:
            cell.font = Font(name="Calibri", size=11)
            cell.border = border
            text = str(cell.value) if cell.value is not None else ""
            multiline = "\n" in text
            if name in {"Billed Amount", "Paid amount"}:
                horizontal, top = "right", multiline
            elif name in {"Finalized Date", "Payment/Check Date"}:
                horizontal, top = "center", multiline
            elif name == "Recheck":
                horizontal, top = "center", False
            elif name == "Claim status":
                top = multiline or len(text) > 25
                horizontal = "left" if top else "center"
            else:
                top = multiline or len(text) > 20
                horizontal = "left"
            cell.alignment = Alignment(horizontal=horizontal,
                                       vertical="top" if top else "center", wrap_text=top)
        length = max(len(str(cell.value)) if cell.value is not None else 0 for cell in cells)
        ws.column_dimensions[header.column_letter].width = min(50, max(minimum_widths[name], length + 3))


def _set_recheck_validation(ws, column, header_row, last_row):
    letter = get_column_letter(column)
    # Keep unrelated validations, including multi-column ranges, intact.
    for validation in list(ws.data_validations.dataValidation):
        ranges = []
        for area in validation.ranges:
            if area.min_col <= column <= area.max_col:
                for left, right in ((area.min_col, column - 1),
                                    (column + 1, area.max_col)):
                    if left <= right:
                        ranges.append(f"{get_column_letter(left)}{area.min_row}:{get_column_letter(right)}{area.max_row}")
            else:
                ranges.append(str(area))
        if ranges:
            validation.sqref = " ".join(ranges)
        else:
            ws.data_validations.dataValidation.remove(validation)
    validation = DataValidation(type="list", formula1='"YES,NO"', allow_blank=True,
                                showDropDown=False)
    ws.add_data_validation(validation)
    validation.add(f"{letter}{header_row + 1}:{letter}{last_row}")


def _copy_report_sheet(source, workbook):
    # These supplemental sheets are generated by our own writer (no drawings).
    name = source.title
    if name in workbook.sheetnames:
        name = f"Checker {name}"
    target = workbook.create_sheet(name)
    for row in source:
        for cell in row:
            new = target.cell(cell.row, cell.column, cell.value)
            new.data_type = cell.data_type
            for attribute in ("font", "fill", "border", "alignment", "protection", "number_format"):
                setattr(new, attribute, copy(getattr(cell, attribute)))
    for key, dimension in source.column_dimensions.items():
        target.column_dimensions[key] = copy(dimension)
        target.column_dimensions[key].parent = target
        for attribute in ("font", "fill", "border", "alignment", "protection", "number_format"):
            setattr(target.column_dimensions[key], attribute, copy(getattr(dimension, attribute)))
    for key, dimension in source.row_dimensions.items():
        target.row_dimensions[key] = copy(dimension)
        target.row_dimensions[key].parent = target
        for attribute in ("font", "fill", "border", "alignment", "protection", "number_format"):
            setattr(target.row_dimensions[key], attribute, copy(getattr(dimension, attribute)))
    target.sheet_view.showGridLines = source.sheet_view.showGridLines
    target.freeze_panes = source.freeze_panes
    target.auto_filter = deepcopy(source.auto_filter)
    target.conditional_formatting = deepcopy(source.conditional_formatting)
    target.sheet_state = source.sheet_state
    target.print_title_rows = source.print_title_rows
    target.page_setup = copy(source.page_setup)
    return target


def generate_preserved_report(*, store, run, spec, statistics, detail_writer):
    from .reporting import ReportError, _group_detail_records, _parse_currency, _parse_date
    output = Path(run.output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    token = uuid.uuid4().hex
    temp = output.with_name(f".{output.stem}.{token}.tmp.xlsx")
    details_path = output.with_name(f".{output.stem}.{token}.details.xlsx")
    workbook = details = None
    try:
        headers = tuple(store.headers(run.id))
        if run.source_ext == ".xlsx":
            workbook = load_workbook(run.snapshot_path, data_only=False)
            ws = workbook[run.sheet_name]
        else:
            from .spreadsheet_source import _csv_settings
            encoding, delimiter = _csv_settings(Path(run.snapshot_path))
            workbook = Workbook()
            ws = workbook.active
            ws.title = run.sheet_name
            ws.append(headers)
            layout = SourceLayout(run.source_ext, run.sheet_name, run.header_row,
                                  run.first_col, headers, encoding, delimiter)
            for _, values in iter_source_rows(run.snapshot_path, layout):
                ws.append(values)
                for cell in ws[ws.max_row]:
                    if isinstance(cell.value, str):
                        cell.data_type = "s"
        positions = {}
        # Exact casing is essential: raw Paid Amount and Claim Status are separate.
        for name in OUTPUT_FIELDS:
            matches = [c.column for c in ws[run.header_row] if c.value == name]
            if name == "Last Action Taken" and not matches:
                matches = [c.column for c in ws[run.header_row]
                           if normalize_header(c.value) in {"lat", "lastactiontaken", "lastaction"}]
            if name == "Recheck" and not matches:
                matches = [c.column for c in ws[run.header_row] if normalize_header(c.value) == "recheck"]
            if not matches:
                index = ws.max_column + 1
                ws.cell(run.header_row, index, name)
                matches = [index]
            positions[name] = matches[0]
        for persisted in store.iter_rows(run.id):
            row = persisted.source_row
            if recheck_disabled(ws.cell(row, positions["Recheck"]).value):
                continue
            result = persisted.result
            records = result.get(spec.result_sheets[0].result_key, []) if spec.result_sheets else []
            if records:
                values = _group_detail_records(records, spec.result_sheets[0])
            elif result.get("claim_status") == "Not Found":
                values = {"claim_status": "Claim Not Found"}
                # Clear stale portal values after a completed search.
                values.update({key: None for name, key in OUTPUT_FIELDS.items()
                               if name not in TRACKING and key != "claim_status"})
            else:
                continue
            for name, key in OUTPUT_FIELDS.items():
                if name in TRACKING or key not in values:
                    continue
                value = values[key]
                if name in {"Billed Amount", "Paid amount"}:
                    value = _parse_currency(value)
                elif name in {"Finalized Date", "Payment/Check Date"}:
                    value = _parse_date(value)
                cell = ws.cell(row, positions[name])
                cell.value = value
                if isinstance(value, str):
                    cell.data_type = "s"
                cell.number_format = ('"$"#,##0.00' if name in {"Billed Amount", "Paid amount"}
                                      else "mm/dd/yyyy" if name in {"Finalized Date", "Payment/Check Date"}
                                      else "@")
        last_row = max(ws.max_row, run.header_row + run.row_count)
        if last_row > run.header_row:
            _set_recheck_validation(ws, positions["Recheck"], run.header_row, last_row)
        apply_ct_output_styling(ws, run.header_row, last_row)
        # Retain the existing multi-claim review and run-summary views as supplements.
        detail_writer(store=store, run=replace(run, output_path=str(details_path)),
                      spec=replace(spec, preserve_source_workbook=False), statistics=statistics)
        details = load_workbook(details_path)
        for sheet in details:
            copied = _copy_report_sheet(sheet, workbook)
            apply_ct_output_styling(copied)
            recheck_column = next((c.column for c in copied[1]
                                   if normalize_header(c.value) == "recheck"), None)
            if recheck_column and copied.max_row > 1:
                _set_recheck_validation(copied, recheck_column, 1, copied.max_row)
        workbook.active = workbook.sheetnames.index(ws.title)
        ws.sheet_state = "visible"
        with temp.open("wb") as handle:
            workbook.save(handle)
        workbook.close()
        workbook = None
        try:
            os.replace(temp, output)
        except PermissionError:
            if not spec.save_copy_if_locked:
                raise
            output = output.with_name(f"{output.stem} - Updated {token[:8]}.xlsx")
            os.replace(temp, output)
        return output
    except OSError as exc:
        raise ReportError(f"Could not save report: {exc}") from exc
    finally:
        if workbook is not None:
            workbook.close()
        if details is not None:
            details.close()
        for path in (temp, details_path):
            try:
                path.unlink(missing_ok=True)
            except OSError:
                pass
